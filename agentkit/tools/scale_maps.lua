-- agentkit/tools/scale_maps.lua — 按键位缩放生成“另一套分辨率”的映射代码（不改运行格式）
--
-- 用法:
--   luajit scale_maps.lua <app|all> <目标WxH> [--ref 2560x1440] [--out 路径]
-- 例:
--   luajit scale_maps.lua wechat 1920x1080
--     -> agentkit/maps/wechat.1920x1080.lua
--   luajit scale_maps.lua all 1600x900 --ref 2560x1440
--
-- 原理: 以参考分辨率(默认本机 2560x1440)的映射为基础，按 sx=TW/RW, sy=TH/RH 线性缩放每个区域。
-- 注意: 只对随分辨率线性缩放的“内容区”成立；固定高度的 bars（工具条/标签栏）如换机请以本脚本生成的
--       结果作为起点，再用 OCR 校验/重试（agentkit 已内置）微调。
local MAPS = os.getenv("AGENTKIT_MAPS") or "/opt/my-agent/agentkit/maps"

local app = arg[1] or "all"
local target = arg[2]
local ref = "2560x1440"
local out
for i = 3, #arg do
    if arg[i] == "--ref" then ref = arg[i + 1]
    elseif arg[i] == "--out" then out = arg[i + 1] end
end

local function parse(s)
    local w, h = tostring(s):match("(%d+)[xX](%d+)")
    return tonumber(w), tonumber(h)
end
local RW, RH = parse(ref)
local TW, TH = parse(target)
assert(RW and TW, "用法: scale_maps.lua <app|all> <WxH> [--ref 2560x1440] [--out 路径]")

local sx, sy = TW / RW, TH / RH
local function sc(c)
    return {
        x = math.floor(c.x * sx + 0.5),
        y = math.floor(c.y * sy + 0.5),
        w = math.max(1, math.floor(c.w * sx + 0.5)),
        h = math.max(1, math.floor(c.h * sy + 0.5)),
    }
end

local function serialize(def, ref, target)
    local L = {}
    L[#L + 1] = string.format("-- generated by tools/scale_maps.lua  ref=%s target=%s (linear)", ref, target)
    L[#L + 1] = "return {"
    L[#L + 1] = string.format("  window = %q,", def.window or "")
    if def.class then L[#L + 1] = string.format("  class = %q,", def.class) end
    L[#L + 1] = "  controls = {"
    local names = {}
    for k in pairs(def.controls or {}) do names[#names + 1] = k end
    table.sort(names)
    for _, k in ipairs(names) do
        local c = sc(def.controls[k])
        local extra = ""
        if def.controls[k].text then extra = extra .. string.format(", text=%q", def.controls[k].text) end
        L[#L + 1] = string.format("    %s = { x=%d, y=%d, w=%d, h=%d%s },",
            k, c.x, c.y, c.w, c.h, extra)
    end
    L[#L + 1] = "  },"
    L[#L + 1] = "}"
    return table.concat(L, "\n") .. "\n"
end

local function list_apps()
    if app ~= "all" then return { app } end
    local t = {}
    local p = io.popen("ls " .. MAPS .. "/*.lua 2>/dev/null")
    for line in p:lines() do
        local base = line:match("([^/]+)%.lua$")
        if base and not base:match("%.%d+x%d+$") then t[#t + 1] = base end  -- 跳过已缩放产物
    end
    p:close()
    return t
end

for _, a in ipairs(list_apps()) do
    local f = loadfile(MAPS .. "/" .. a .. ".lua")
    if f then
        local def = f()
        local op = out or string.format("%s/%s.%dx%d.lua", MAPS, a, TW, TH)
        local w = assert(io.open(op, "w"))
        w:write(serialize(def, ref, target))
        w:close()
        print(string.format("  %-12s -> %s", a, op))
    end
end
