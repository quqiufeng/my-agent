-- agentkit/record.lua — 录制器：把对适配器的一串调用（many records）固化成可回放的 Lua 脚本
--   local r = ak.record("google")
--   r:search("DeepSeek")            -- 执行并记录
--   local lines = r:read_results()  -- 执行并记录
--   r:save("/opt/my-agent/agentkit/flows/google_search.lua")  -- 生成脚本
--   r:replay()                      -- 直接回放本次记录
local M = {}

local Rec = {}

local function ser(v)
    local t = type(v)
    if t == "string" then return string.format("%q", v)
    elseif t == "number" or t == "boolean" then return tostring(v)
    elseif t == "table" then
        local parts = {}
        for i = 1, #v do parts[#parts + 1] = ser(v[i]) end
        return "{" .. table.concat(parts, ", ") .. "}"
    end
    return "nil"
end

-- 记录一次调用（method + args），并实际执行
Rec.__index = function(self, k)
    local v = rawget(Rec, k)
    if v ~= nil then return v end
    return function(_, ...)
        local adapter = rawget(self, "adapter")
        local fn = adapter[k]
        if not fn then error("record: adapter has no method '" .. k .. "'") end
        local packed = table.pack(...)
        rawget(self, "steps")[#rawget(self, "steps") + 1] =
            { fn = k, args = packed, n = packed.n }
        return fn(...)
    end
end

function Rec:to_lua()
    local L = {}
    L[#L + 1] = "-- auto-generated by agentkit.record"
    L[#L + 1] = "package.path = \"/opt/my-agent/?.lua;/opt/my-agent/?/init.lua;\" .. package.path"
    L[#L + 1] = "local ak = require(\"agentkit\")"
    L[#L + 1] = ("local app = ak.app(%q)"):format(rawget(self, "app"))
    for _, s in ipairs(rawget(self, "steps")) do
        local args = {}
        for i = 1, s.n do args[#args + 1] = ser(s.args[i]) end
        L[#L + 1] = ("local r = app:%s(%s)"):format(s.fn, table.concat(args, ", "))
    end
    L[#L + 1] = "return r"
    return table.concat(L, "\n") .. "\n"
end

function Rec:save(path)
    local f = assert(io.open(path, "w"))
    f:write(self:to_lua())
    f:close()
    return path
end

function Rec:replay()
    local adapter = rawget(self, "adapter")
    local last
    for _, s in ipairs(rawget(self, "steps")) do
        local args = {}
        for i = 1, s.n do args[i] = s.args[i] end
        last = adapter[s.fn](table.unpack(args, 1, s.n))
    end
    return last
end

function Rec:dump()
    local out = {}
    for i, s in ipairs(rawget(self, "steps")) do
        out[#out + 1] = string.format("%d) %s", i, s.fn)
    end
    return out
end

function M.new(app)
    local adapter = require("agentkit.adapters." .. app)
    return setmetatable({ app = app, adapter = adapter, steps = {} }, Rec)
end

return M
