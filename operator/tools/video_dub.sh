#!/usr/bin/env bash
# tools/video_dub.sh — 给已有视频配音+字幕（LuaJIT 编排 + ffmpeg/音色引擎）
# @desc 给已有视频配音+字幕（可克隆音色）；先用 --probe 生成配音比对时长，确保不超视频，再合成
# @usage tools/video_dub.sh <视频> "文案1|文案2|…" [--probe] [--speed 0.85] [--fit] [--ref 参考.wav] [--voice 名] [--out out.mp4] [--to 会话] [--send] [--keep-audio] [--fg]
# @rule **生成抖音素材 / 给视频配音+字幕 / 带货引流视频**：说“**生成抖音素材** / 做抖音素材 / 生成素材 / 给这个视频配音+字幕 / 给视频配字幕 / 做带货引流视频 / 给这个视频配文案和配音”→ **根据视频/商品信息自己推理写文案**（像真人口播，别念参数：①钩子→②品牌价值→③口语串讲卖点→④收尾；不出现品牌名；「防水」改「不怕水」；`App`写「官方软件」；每段≈20字、长度均衡、**可短不可超视频时长**；结尾固定「想捡漏的来我直播间」），再用本工具先 `--probe`（自动前台）比对时长、后 `--fg` 合成。默认出**3 条不同文案**（同一素材），**必须一条跑完再跑下一条（串行，切勿并发）**；可加 `--ss/--trim-end` 换裁剪段。**默认音色=克隆「话术」**（换音色 `--voice`）。默认不发微信（`--send` 才发）。
# @order 15
set -uo pipefail
DIR="$(cd "$(dirname "$0")" && pwd)"
exec luajit "$DIR/video_dub.lua" "$@"
